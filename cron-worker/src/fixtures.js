// 与 data.js 同样的对阵生成：R1=[T1vT2,T3vT4] R2=[T1vT3,T4vT2] R3=[T1vT4,T2vT3]
export function buildGroupFixtures() {
  const out = [];
  GROUP_NAMES.forEach((gName, gi) => {
    const teams = TEAM_LIST.slice(gi * 4, gi * 4 + 4);
    const [t0, t1, t2, t3] = teams;
    const rounds = [
      [[t0, t1], [t2, t3]],
      [[t0, t2], [t3, t1]],
      [[t0, t3], [t1, t2]],
    ];
    rounds.forEach((pairings, ri) => {
      pairings.forEach((pair, pi) => {
        const [date, time] = SCHED[gName][ri][pi];
        const [mm, dd] = date.split('-');
        out.push({
          id: `G${gName}-R${ri + 1}-${pi + 1}`,
          group: gName,
          round: ri + 1,
          home: pair[0],
          away: pair[1],
          // 北京时间（UTC+8）
          kickoffBeijing: `2026-${date}T${time}:00+08:00`,
          dateLabel: `${parseInt(mm, 10)}月${parseInt(dd, 10)}日`,
        });
      });
    });
  });
  return out;
}
